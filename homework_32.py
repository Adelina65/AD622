# Задание:
# Создайте приложение, которое содержит заголовок "Мой первый дашборд" (тег H1) и линейный график (Line Chart)
# функций y = x² для значений x от 1 до 5.


import plotly.express as px
from dash import Dash, dcc, html


x = [1, 2, 3, 4, 5]
y = [1, 4, 9, 16, 25]
fig = px.line(x=x, y=y,  title="График функции Y = X²")

app = Dash()
app.layout = html.Div([
    html.H1("Мой первый дашборд"),
    dcc.Graph(figure=fig)
])
if __name__ == '__main__':
    app.run(debug=True)