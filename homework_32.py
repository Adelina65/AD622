# показывающий изменения температуры в вашем городе по месяцам.


import pandas as pd
import plotly.express as px

# Я НЕ ЗНАЮ КАК СДЕЛАТЬ, ЧТОБЫ АНИМАЦИЯ ОТОБРАЖАЛАСЬ МЕДЛЕННО;

data = {
    "Месяц": ["Янв", "Фев", "Март", "Апр", "Май", "Июн", "Июл", "Авг", "Сен", "Окт", "Ноя", "Дек"],
    "Температура": [0.0, 5.3, 7.4, 12.5, 21.7, 30.5, 35.1, 35.8, 25.6, 12.3, 6.8, 2.3],
}
df = pd.DataFrame(data)

fig = px.bar(
    df,
    x="Месяц",
    y="Температура",
    animation_frame="Месяц",
    color="Температура",
    range_y=[-5, 40],
    title="Погода в Краснодаре за 12 месяцев"
)

fig.show()



