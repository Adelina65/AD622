# •	Электроника — 450 тыс. руб.
# •	Одежда — 320 тыс. руб.
# •	Книги — 180 тыс. руб.
# •	Дом и сад — 290 тыс. руб.
# Постройте вертикальную столбчатовую диаграмму. Задайте для каждого столбика свой цвет, настройте ширину столбцов и добавьте сетку только по оси Y,
# чтобы было удобнее считывать значения.

# "коды" на цвета смотрела в интернете

categories = ['Электроника', 'Одежда', 'Книги', 'Дом и сад']
sales = [450, 320, 180, 290]
plt.figure(figsize=(8,5))
plt.bar(categories, sales, color = ['#34495e', '#f1948a', '#85c1e9', '#f7dc6f'], edgecolor = 'black', width = 0.4)
plt.title('Сравнение объемов продаж', fontsize = 14, fontweight = 'bold')
