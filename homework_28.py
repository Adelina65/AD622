# Задание 1. Зависимость цены квартиры от её площади
# Условие:
# Имеются данные о площади 10 квартир (в кв. метрах) и их стоимости (в млн рублей).
# •	Площадь: [35, 42, 54, 62, 71, 85, 93, 104, 115, 128]
# •	Цена: [8.4, 11.3, 14.6, 19.8, 22.1, 28.9, 33.5, 41.6, 49.5, 58.9]
# Постройте диаграмму рассеяния. Сделайте маркеры в виде круглых точек синего цвета, добавьте прозрачность, чтобы точки не перекрывали друг друга, и подпишите оси.


import matplotlib.pyplot as plt


s_home = [35, 42, 54, 62, 71, 85, 93, 104, 115, 128]
price = [8.4, 11.3, 14.6, 19.8, 22.1, 28.9, 33.5, 41.6, 49.5, 58.9]
plt.scatter(s_home, price, color='blue', alpha=0.6, marker='o')
plt.title('Зависимость цены квартиры от её площади', fontsize = 14, fontweight = 'bold')
plt.xlabel('Площадь квартир (кв. метр) ', fontsize = 12)
plt.ylabel('Стоимость (млн. руб.) ', fontsize = 12)
plt.show()


